"""
GENERATE · BRIDGE
Resolves every `pat` in content_bridge.ENTRIES against the 130 verified
solutions and records the exact line it matched, with the solution id and line
number. An entry that claims an idiom the solutions never actually use fails
here rather than shipping.

Writes build/content_bridge_out.py. Re-run after editing an entry or a solution.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import content_bridge as B  # noqa: E402
import content_c  # noqa: E402
import content_ds_problems as DSP  # noqa: E402

HERE = Path(__file__).resolve().parent
AUTHOR_CAP = 120


def corpus() -> dict[str, list[tuple[str, int, str]]]:
    """lang -> [(solution id, line number, text)], in the order they appear."""
    out: dict[str, list[tuple[str, int, str]]] = {"c": [], "py": [], "r": []}
    for s in content_c.SETS:
        for it in s["items"]:
            for i, line in enumerate(it["sol"].split("\n"), 1):
                if line.strip():
                    out["c"].append((it["id"], i, line))
    for s in DSP.SETS:
        for it in s["items"]:
            for lang in ("py", "r"):
                for i, line in enumerate(it[lang].split("\n"), 1):
                    if line.strip():
                        out[lang].append((it["id"], i, line))
    return out


def main() -> int:
    C = corpus()
    resolved: dict[str, dict] = {}
    missing: list[tuple[str, str, str]] = []
    mined = authored = absent = 0

    for e in B.ENTRIES:
        row = {"id": e["id"], "sec": e["sec"], "en": e["en"], "note": e.get("note", "")}
        for lang in ("c", "py", "r"):
            cell = e.get(lang) or {}
            if cell.get("no"):
                row[lang] = {"kind": "no", "text": cell["no"]}
                absent += 1
                continue
            if cell.get("lit"):
                row[lang] = {"kind": "lit", "code": cell["lit"]}
                authored += 1
                continue
            pat = cell.get("pat")
            if not pat:
                row[lang] = {"kind": "no", "text": "Not written yet."}
                absent += 1
                continue
            rx = re.compile(pat)
            hit = None
            for sid, ln, text in C[lang]:
                if rx.search(text):
                    hit = (sid, ln, text.strip())
                    break
            if hit is None:
                missing.append((e["id"], lang, pat))
                row[lang] = {"kind": "no",
                             "text": "No verified solution uses this yet."}
                absent += 1
            else:
                row[lang] = {"kind": "mined", "code": hit[2],
                             "src": hit[0], "line": hit[1]}
                mined += 1
        resolved[e["id"]] = row

    dst = HERE / "content_bridge_out.py"
    dst.write_text(
        '"""GENERATED by build/gen_bridge.py — do not edit by hand.\n\n'
        "Each language cell is either a line lifted verbatim from a solution that\n"
        "passes verify_c.py / verify_ds.py (with the solution id and line number),\n"
        "an authored line, or a written reason the language has no equivalent.\n"
        '"""\n\nfrom __future__ import annotations\n\n'
        "ROWS = " + json.dumps(resolved, indent=1, sort_keys=False) + "\n",
        encoding="utf-8")

    print(f"wrote {dst}")
    total_cells = mined + authored + absent
    print(f"  mined from verified solutions : {mined}  "
          f"({mined * 100 // max(total_cells - absent, 1)}% of the drillable cells)")
    print(f"  authored                      : {authored}  (cap {AUTHOR_CAP}, each one compiled or run by verify_authored.py)")
    print(f"  absence cells with a reason   : {absent}")
    if missing:
        print(f"\n{len(missing)} pattern(s) matched nothing:")
        for eid, lang, pat in missing:
            print(f"  {eid:10s} {lang:3s} {pat}")
    if authored > AUTHOR_CAP:
        print(f"\nOVER CAP: {authored} authored cells, cap is {AUTHOR_CAP}.")
        return 1
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
